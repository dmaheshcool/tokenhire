export function t(path, vars) {
  let v = path.split(".").reduce((o, key) => (o == null ? o : o[key]), STRINGS);
  if (typeof v !== "string") return path;
  if (vars) v = v.replace(/\{(\w+)\}/g, (m, key) => (vars[key] != null ? String(vars[key]) : m));
  return v;
}
